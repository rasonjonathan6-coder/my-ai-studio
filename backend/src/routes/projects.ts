router.get('/:id/file', asyncHandler(async (req, res) => {
  const project = await loadOwnedProject(req);
  const relPath = req.query.path;
  if (typeof relPath !== 'string' || relPath.length === 0) {
    throw new HttpError(400, 'query parameter "path" is required', 'missing_path');
  }
  const ws = new WorkspaceService(project!.id);
  try {
    const file = await ws.read(relPath);
    res.json(file);
  } catch (err) {
    if (err instanceof PathSecurityError) {
      await audit({ userId: req.user!.id, projectId: project!.id, action: 'file.read', outcome: 'path_traversal_blocked', ip: req.ip ?? null, detail: { path: relPath } });
      throw new HttpError(400, 'invalid file path', 'invalid_path');
    }
    throw new HttpError(404, err instanceof Error ? err.message : 'file not found', 'file_not_found');
  }
}));

