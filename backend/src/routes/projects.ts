router.post('/', asyncHandler(async (req, res) => {
  const body = validate(createProjectSchema, req.body);
  const template = findTemplate(body.template);
  if (body.template !== 'blank' && !template) {
    throw new HttpError(400, `unknown template: ${body.template}`, 'unknown_template');
  }
  const kind: ProjectKind = body.kind ?? template?.kind ?? 'generic';

  // Slug uniqueness is per owner, so retry with a suffix on collision.
  let slug = slugify(body.name);
  for (let attempt = 0; attempt < 5; attempt += 1) {
    const candidate = attempt === 0 ? slug : `${slug}-${Math.random().toString(36).slice(2, 6)}`;
    try {
      const project = await createProject({
        ownerId: req.user!.id,
        name: body.name,
        slug: candidate,
        description: body.description,
        template: template?.id ?? 'blank',
        kind,
        packageName: template?.packageName ?? null,
      });
      slug = candidate;

      const ws = new WorkspaceService(project.id);
      await ws.ensure();
      await applyTemplate(project.id, template?.id ?? 'blank', project.name);

      // Android projects need a real Gradle wrapper to be buildable. The files
      // are installed from vendored assets rather than generated by `gradle
      // wrapper`, which can hang for minutes on a cold environment.
      if (kind === 'android') {
        const wrapper = await ensureGradleWrapper(project.id);
        logger.info('gradle wrapper install', {
          projectId: project.id, ok: wrapper.ok, detail: wrapper.detail,
        });
      }

      await audit({ userId: req.user!.id, projectId: project.id, action: 'project.create', ip: req.ip ?? null, detail: { template: project.template } });
      res.status(201).json({ project });
      return;
    } catch (err) {
      const message = err instanceof Error ? err.message : String(err);
      if (/projects_owner_slug_key|duplicate key/i.test(message) && attempt < 4) continue;
      throw err;
    }
  }
  throw new HttpError(500, 'could not allocate a unique project slug', 'slug_allocation_failed');
}));

