function projectIdParam(req: Request): string {
  const id = req.params.id;
  if (!id) throw new HttpError(400, 'project id is required', 'invalid_project_id');
  return id;
}

async function loadOwnedProject(req: Request, required = true) {
  const id = projectIdParam(req);
  const owner = req.user!.id;
  const project = await getProjectForOwner(id, owner);
  if (!project) {
    // Distinguish malformed ids from genuine authorization failures in audit logs
    // while returning the same response, so ids cannot be probed.
    await audit({ userId: owner, action: 'project.access', outcome: 'denied', ip: req.ip ?? null, detail: { id } });
    if (required) throw new HttpError(404, 'project not found', 'project_not_found');
  }
  return project;
}

