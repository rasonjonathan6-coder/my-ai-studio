#!/usr/bin/env node
/**
 * Materialises the three Android test projects into `android-samples/` using the
 * exact same template code the running backend uses. This keeps the CI Android
 * build honest: it compiles the same sources users get, not a hand-written
 * lookalike that could drift from the product.
 */
import fs from 'node:fs/promises';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import { runCommand } from '../backend/src/services/commandRunner.ts';

const here = path.dirname(fileURLToPath(import.meta.url));
const repoRoot = path.resolve(here, '..');
const outRoot = path.join(repoRoot, 'android-samples');

const SAMPLES = [
  { dir: 'hello', template: 'android-hello', name: 'Hello Android' },
  { dir: 'calculator', template: 'android-calculator', name: 'Simple Calculator' },
  { dir: 'translator', template: 'android-floating-translator', name: 'Floating AI Translator' },
];

async function dirExists(p) {
  try {
    await fs.access(p);
    return true;
  } catch {
    return false;
  }
}

const { androidTemplateFiles } = await import('../backend/src/services/templates.ts');

for (const sample of SAMPLES) {
  const target = path.join(outRoot, sample.dir);
  await fs.rm(target, { recursive: true, force: true });
  await fs.mkdir(target, { recursive: true });

  const files = androidTemplateFiles(sample.template, sample.name);
  for (const [rel, content] of Object.entries(files)) {
    const abs = path.join(target, rel);
    await fs.mkdir(path.dirname(abs), { recursive: true });
    await fs.writeFile(abs, content, 'utf8');
  }

  // A real Gradle wrapper so CI and users can run ./gradlew without a Gradle install.
  const wrapper = await runCommand({
    cwd: target,
    command: 'gradle wrapper --gradle-version 8.9 --no-daemon',
    timeoutMs: 180000,
  });
  if (wrapper.exitCode !== 0) {
    console.error(`gradle wrapper FAILED for ${sample.dir}\n${wrapper.stdout}\n${wrapper.stderr}`);
    process.exit(1);
  }

  const jar = path.join(target, 'gradle', 'wrapper', 'gradle-wrapper.jar');
  if (!(await dirExists(jar))) {
    console.error(`gradle-wrapper.jar missing after wrapper task for ${sample.dir}`);
    process.exit(1);
  }

  // Committing build output or caches would bloat the repo and hide staleness.
  await fs.writeFile(path.join(target, '.gitignore'), 'build/\n.gradle/\nlocal.properties\n*.apk\n.kotlin/\n', 'utf8');
  console.log(`generated android-samples/${sample.dir} (${Object.keys(files).length} files + gradle wrapper)`);
}

// A root-level .gitignore plus a note keeps the directory self-explanatory.
await fs.writeFile(
  path.join(outRoot, 'README.md'),
  `# Android sample projects

Generated by \`scripts/generate-android-samples.mjs\` from the same template code the
backend uses (\`backend/src/services/templates.ts\`). Do not hand-edit: regenerate instead.

| Directory | Template | Purpose |
| --- | --- | --- |
| \`hello/\` | android-hello | Minimal single-activity app. |
| \`calculator/\` | android-calculator | Unit-tested arithmetic plus a Compose-free UI. |
| \`translator/\` | android-floating-translator | Accessibility service plus overlay, translating selected text. |

Each project is independent and has a real Gradle wrapper:

\`\`\`bash
cd android-samples/calculator
./gradlew test
./gradlew assembleDebug
\`\`\`

The debug APK lands in \`app/build/outputs/apk/debug/app-debug.apk\`.

Some Android apps block the accessibility APIs the translator relies on, so its
behaviour is not universal.
`,
  'utf8',
);

console.log('done');
